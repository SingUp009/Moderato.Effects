using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Moderato.Effects.SourceGenerator;

/// <summary>Implements <c>IUnionCase</c> on <c>[Error]</c> unions, for each case and each case of a case.</summary>
[Generator]
public sealed class ErrorGenerator : IIncrementalGenerator
{
    private sealed record Model(Declaration? Declaration, EquatableArray<CasePath> Cases, EquatableArray<DiagnosticInfo> Diagnostics);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Moderato.Effects.ErrorAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (ctx, _) => Describe((INamedTypeSymbol)ctx.TargetSymbol, (TypeDeclarationSyntax)ctx.TargetNode));

        context.RegisterSourceOutput(models, static (spc, model) =>
        {
            foreach (var diagnostic in model.Diagnostics) spc.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (model.Declaration is { } declaration && model.Cases.Length > 0)
                spc.AddSource($"{Hint(declaration)}.Error.g.cs", Emit(declaration, model.Cases));
        });
    }

    private static Model Describe(INamedTypeSymbol type, TypeDeclarationSyntax node)
    {
        var location = node.Identifier.GetLocation();
        if (!Shapes.IsUnion(type) || !Shapes.IsPartial(node))
            return Failed(DiagnosticInfo.Create(Diagnostics.NeedsPartialUnion, location, "Error", type.Name));
        if (Shapes.Unsupported("Error", type, location) is { } unsupported) return Failed(unsupported);

        var cases = new System.Collections.Generic.List<CasePath>();
        var diagnostics = new System.Collections.Generic.List<DiagnosticInfo>();
        foreach (var entry in Shapes.Reachable(type).OrderBy(static e => e.Key, System.StringComparer.Ordinal))
        {
            var paths = entry.Value;
            if (paths.Count == 1)
            {
                cases.Add(paths[0]);
                continue;
            }

            // A direct case stays usable; only the nested routes to the same type are ambiguous.
            if (paths.FirstOrDefault(static p => p.IsDirect) is { } direct) cases.Add(direct);
            var routes = string.Join(", ", paths.Select(static p => string.Join(" > ", p.Steps.Items.Select(Short))));
            diagnostics.Add(DiagnosticInfo.Create(Diagnostics.AmbiguousCase, location, type.Name, Short(entry.Key), routes));
        }

        return new Model(Shapes.Declare(type, node), cases.ToEquatableArray(), diagnostics.ToEquatableArray());
    }

    private static Model Failed(DiagnosticInfo diagnostic) => new(null, default, new[] { diagnostic }.ToEquatableArray());

    private static string Short(string fullName) => fullName.Substring(fullName.LastIndexOf('.') + 1);

    private static string Hint(Declaration declaration) => declaration.Namespace.Length == 0 ? declaration.Name : $"{declaration.Namespace}.{declaration.Name}";

    private static string Emit(Declaration declaration, EquatableArray<CasePath> cases)
    {
        var self = declaration.Name;
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n\n").Append(declaration.Open());
        sb.Append($"partial {declaration.Keyword} {self} : ");
        sb.Append(string.Join(", ", cases.Select(c => $"global::Moderato.Effects.IUnionCase<{self}, {c.Target}>")));
        sb.Append("\n{\n");
        foreach (var path in cases)
        {
            var iface = $"global::Moderato.Effects.IUnionCase<{self}, {path.Target}>";
            sb.Append($"    static {self} {iface}.From({path.Target} value) => {Shapes.Widen(path, "value")};\n\n");
            sb.Append($"    static bool {iface}.TryGet({self} self, out {path.Target} value)\n    {{\n");
            sb.Append($"        if ({Shapes.Narrow(path, "self", "found")})\n        {{\n            value = found;\n            return true;\n        }}\n\n");
            sb.Append("        value = default!;\n        return false;\n    }\n\n");
        }

        sb.Length -= 1;
        sb.Append("}\n");
        return sb.ToString();
    }
}
