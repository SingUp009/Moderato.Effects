using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Moderato.Effects.SourceGenerator;

/// <summary>Implements <c>IHas&lt;T&gt;</c> on <c>[Environment]</c> types, per primary constructor parameter.</summary>
[Generator]
public sealed class EnvironmentGenerator : IIncrementalGenerator
{
    private sealed record Service(string Type, string Parameter);

    private sealed record Model(Declaration? Declaration, EquatableArray<Service> Services, EquatableArray<DiagnosticInfo> Diagnostics);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Moderato.Effects.EnvironmentAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (ctx, _) => Describe((INamedTypeSymbol)ctx.TargetSymbol, (TypeDeclarationSyntax)ctx.TargetNode, ctx.SemanticModel.Compilation));

        context.RegisterSourceOutput(models, static (spc, model) =>
        {
            foreach (var diagnostic in model.Diagnostics) spc.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (model.Declaration is { } declaration && model.Diagnostics.Length == 0 && model.Services.Length > 0)
            {
                spc.AddSource($"{declaration.Hint}.Environment.g.cs", Emit(declaration, model.Services));
            }
        });
    }

    private static Model Describe(INamedTypeSymbol type, TypeDeclarationSyntax node, Compilation compilation)
    {
        var location = node.Identifier.GetLocation();
        if (!Shapes.IsPartial(node)) return Failed(DiagnosticInfo.Create(Diagnostics.NeedsPartialType, location, type.Name));
        if (Shapes.Unsupported("Environment", type, location) is { } unsupported) return Failed(unsupported);

        var primary = PrimaryConstructor(type);
        if (primary is null) return Failed(DiagnosticInfo.Create(Diagnostics.NeedsPrimaryConstructor, location, type.Name));

        var services = new List<Service>();
        var diagnostics = new List<DiagnosticInfo>();
        var providers = new Dictionary<string, string>();
        foreach (var parameter in primary.Parameters)
        {
            var parameterLocation = parameter.Locations.FirstOrDefault() ?? location;
            var exposed = parameter.GetAttributes()
                .Where(static a => a.AttributeClass is { IsGenericType: true } c
                    && c.ConstructedFrom.ToDisplayString() == "Moderato.Effects.ExposeAttribute<T>")
                .Select(static a => a.AttributeClass!.TypeArguments[0])
                .ToList();
            if (exposed.Count == 0) exposed.Add(parameter.Type);

            foreach (var serviceType in exposed)
            {
                if (!compilation.ClassifyCommonConversion(parameter.Type, serviceType).IsImplicit)
                {
                    diagnostics.Add(DiagnosticInfo.Create(
                        Diagnostics.ExposeNotConvertible, parameterLocation, parameter.Name, parameter.Type.ToDisplayString(), serviceType.ToDisplayString()));
                    continue;
                }

                var name = Shapes.Name(serviceType);
                if (providers.TryGetValue(name, out var first))
                {
                    diagnostics.Add(DiagnosticInfo.Create(Diagnostics.DuplicateService, parameterLocation, serviceType.ToDisplayString(), first, parameter.Name));
                    continue;
                }

                providers[name] = parameter.Name;
                services.Add(new Service(name, parameter.Name));
            }
        }

        return new Model(Shapes.Declare(type, node), services.ToEquatableArray(), diagnostics.ToEquatableArray());
    }

    // A record's copy constructor is not the primary constructor.
    private static IMethodSymbol? PrimaryConstructor(INamedTypeSymbol type)
        => type.InstanceConstructors.FirstOrDefault(c =>
            c.DeclaringSyntaxReferences.Any(static r => r.GetSyntax() is TypeDeclarationSyntax { ParameterList: not null })
            && !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, type)));

    private static Model Failed(DiagnosticInfo diagnostic) => new(null, default, new[] { diagnostic }.ToEquatableArray());

    private static string Emit(Declaration declaration, EquatableArray<Service> services)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n\n").Append(declaration.Open());
        sb.Append($"partial {declaration.Keyword} {declaration.Name} : ");
        sb.Append(string.Join(", ", services.Select(static s => $"global::Moderato.Effects.IHas<{s.Type}>")));
        sb.Append("\n{\n");
        foreach (var service in services)
        {
            sb.Append($"    {service.Type} global::Moderato.Effects.IHas<{service.Type}>.Service => @{service.Parameter};\n");
        }

        sb.Append("}\n");
        return sb.ToString();
    }
}
