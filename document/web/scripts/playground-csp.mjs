import { createHash } from 'node:crypto';
import { appendFileSync, globSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fromHtml } from 'hast-util-from-html';
import { selectAll } from 'hast-util-select';

const EXECUTABLE_TYPES = new Set(['', 'module', 'text/javascript', 'application/javascript']);

// Tutorial pages carry the playground. Its worker is bundled into /_astro/ and takes its policy from
// its own response, so it gets the same one; on other bundled files the header has no effect.
const PAGES = 'tutorial/**/index.html';
const PATHS = ['/tutorial/*', '/_astro/*'];

function textOf(node) {
  if (node.type === 'text') return node.value;
  return (node.children ?? []).map(textOf).join('');
}

/** The hashes of every inline script the built tutorial pages execute, in CSP source form. */
export function inlineScriptHashes(dist) {
  const hashes = new Set();
  for (const page of globSync(PAGES, { cwd: dist })) {
    const tree = fromHtml(readFileSync(join(dist, page), 'utf8'));
    for (const script of selectAll('script:not([src])', tree)) {
      if (!EXECUTABLE_TYPES.has(String(script.properties.type ?? '').toLowerCase())) continue;
      hashes.add(`'sha256-${createHash('sha256').update(textOf(script)).digest('base64')}'`);
    }
  }
  return [...hashes].sort();
}

/** The Content-Security-Policy for pages with the playground and for its runner worker. */
export function playgroundPolicy(dist) {
  return [
    "default-src 'self'",
    // The .NET runtime compiles WebAssembly; Starlight's inline scripts are allowed by hash so others are not.
    `script-src 'self' 'wasm-unsafe-eval' ${inlineScriptHashes(dist).join(' ')}`,
    // Expressive Code colors code with style attributes.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/**
 * Adds the playground's Content-Security-Policy to the built `_headers`. It is computed after the
 * build because the inline scripts it allows change with Starlight and Astro versions.
 */
export function writePlaygroundCsp(dist) {
  const policy = playgroundPolicy(dist);
  const rules = PATHS.map((path) => `${path}\n  Content-Security-Policy: ${policy}\n`).join('\n');
  appendFileSync(join(dist, '_headers'), `\n# Generated by scripts/playground-csp.mjs from the built tutorial pages.\n${rules}`);
}
